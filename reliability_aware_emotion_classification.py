required = ["val_logits_calibrated", "test_logits_calibrated", "val_labels", "test_labels"]
missing = [k for k in required if k not in s2]
if missing:
    print("Stage 2 keys:", list(s2.keys()))
    raise KeyError(f"Stage 2 missing keys: {missing}")

val_logits = s2["val_logits_calibrated"].float()
test_logits = s2["test_logits_calibrated"].float()
val_y = s2["val_labels"].long().numpy()
test_y = s2["test_labels"].long().numpy()

val_probs = torch.softmax(val_logits, dim=1)
test_probs = torch.softmax(test_logits, dim=1)

val_pred = val_probs.argmax(dim=1).numpy()
test_pred = test_probs.argmax(dim=1).numpy()

# -----------------------------
# Uncertainty definition
# Higher value = MORE uncertain
# -----------------------------
UNCERTAINTY_MODE = "entropy"   # "entropy", "margin", "var_ratio", "confidence"
eps = 1e-12

def u_entropy(p):
    return -(p * (p + eps).log()).sum(dim=1)

def u_var_ratio(p):
    conf = p.max(dim=1).values
    return 1.0 - conf

def u_confidence(p):
    conf = p.max(dim=1).values
    return 1.0 - conf

def u_margin(p):
    top2 = torch.topk(p, k=2, dim=1).values
    mar = top2[:, 0] - top2[:, 1]  # higher = more confident
    return 1.0 - mar               # convert to uncertainty

def compute_u(p, mode):
    mode = mode.lower()
    if mode == "entropy":
        return u_entropy(p).numpy()
    if mode in ["var_ratio", "variation_ratio"]:
        return u_var_ratio(p).numpy()
    if mode == "confidence":
        return u_confidence(p).numpy()
    if mode == "margin":
        return u_margin(p).numpy()
    raise ValueError(f"Unknown UNCERTAINTY_MODE: {mode}")

val_u = compute_u(val_probs, UNCERTAINTY_MODE)
test_u = compute_u(test_probs, UNCERTAINTY_MODE)

# -----------------------------
# Sweep coverages (as in your methodology)
# -----------------------------
coverages = [1.00, 0.95, 0.90, 0.85, 0.80, 0.70]

rows = []
thresholds = {}

for cov in coverages:
    # accept if u <= threshold; choose threshold on VAL to hit desired coverage
    thr = float(np.quantile(val_u, cov))
    thresholds[cov] = thr

    val_accept = (val_u <= thr)
    test_accept = (test_u <= thr)

    # Metrics on accepted subset
    yv = val_y[val_accept]; pv = val_pred[val_accept]
    yt = test_y[test_accept]; pt = test_pred[test_accept]

    val_acc = accuracy_score(yv, pv) if len(yv) else np.nan
    val_mf1 = f1_score(yv, pv, average="macro") if len(yv) else np.nan
    val_risk = 1.0 - val_acc if len(yv) else np.nan

    test_acc = accuracy_score(yt, pt) if len(yt) else np.nan
    test_mf1 = f1_score(yt, pt, average="macro") if len(yt) else np.nan
    test_risk = 1.0 - test_acc if len(yt) else np.nan

    rows.append({
        "mode": UNCERTAINTY_MODE,
        "target_coverage_val": cov,
        "threshold_from_val": thr,
        "val_coverage_actual": float(val_accept.mean()),
        "val_accuracy_accepted": float(val_acc),
        "val_macro_f1_accepted": float(val_mf1),
        "val_risk_accepted": float(val_risk),
        "test_coverage_actual": float(test_accept.mean()),
        "test_accuracy_accepted": float(test_acc),
        "test_macro_f1_accepted": float(test_mf1),
        "test_risk_accepted": float(test_risk),
        "accepted_test_n": int(test_accept.sum()),
        "rejected_test_n": int((~test_accept).sum()),
    })

df = pd.DataFrame(rows)
