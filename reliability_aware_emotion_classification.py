# -----------------------------
# ECE (Expected Calibration Error)
# -----------------------------
@torch.no_grad()
def ece_score(probs: torch.Tensor, labels: torch.Tensor, n_bins: int = 15) -> float:
    conf, pred = probs.max(dim=1)
    acc = (pred == labels).float()
    bins = torch.linspace(0, 1, n_bins + 1, device=probs.device)
    ece = torch.zeros(1, device=probs.device)

    for i in range(n_bins):
        lo, hi = bins[i], bins[i+1]
        in_bin = (conf > lo) & (conf <= hi)
        if in_bin.any():
            bin_acc = acc[in_bin].mean()
            bin_conf = conf[in_bin].mean()
            bin_frac = in_bin.float().mean()
            ece += torch.abs(bin_acc - bin_conf) * bin_frac

    return float(ece.item())

# -----------------------------
# Temperature scaling model
# -----------------------------
class TemperatureScaler(nn.Module):
    def __init__(self, init_T=1.0):
        super().__init__()
        self.log_T = nn.Parameter(torch.log(torch.tensor([init_T], dtype=torch.float32)))

    def forward(self, logits):
        T = torch.exp(self.log_T)
        return logits / T

    def temperature(self):
        return float(torch.exp(self.log_T).detach().cpu().item())

